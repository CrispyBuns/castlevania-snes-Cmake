func rgbTo15Bit(r, g, b byte) uint16 {
	r5 := uint16((uint32(r) * 31) / 255)
	g5 := uint16((uint32(g) * 31) / 255)
	b5 := uint16((uint32(b) * 31) / 255)
	return (b5 << 10) | (g5 << 5) | r5
}

func main() {

	// open a file to read the palette from
	filename := os.Args[1]
	fmt.Printf("Reading palette from %s\n", filename)
	file, _ := os.OpenFile(filename, os.O_RDONLY, 0644)
	br := bufio.NewReader(file)

	const colorCount = 64
	const colorsPerLine = 8
	for i := 0; i < colorCount; i += colorsPerLine {
		fmt.Print(".word ")
		for j := 0; j < colorsPerLine; j++ {			
			r, err := br.ReadByte()
			g, _ := br.ReadByte()
			b, _ := br.ReadByte()

			if err != nil && !errors.Is(err, io.EOF) {
				fmt.Println(err)
				break
			}

			color15 := rgbTo15Bit(r, g, b)
			fmt.Printf("$%04X", color15)
			if j < colorsPerLine-1 {
				fmt.Print(", ")
			}
		}
		fmt.Println()
	}
}